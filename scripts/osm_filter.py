#!/usr/bin/env python3
"""
Print an osmium tags-filter expression file matching every object the imposm
mapping (imposm/*.py) imports.

Pre-filtering a Geofabrik extract with these expressions shrinks it by ~95%
without changing what ends up in the database, which makes the imposm import
much faster and far less hungry for disk.

Usage:
    python3 scripts/osm_filter.py > filter.txt
    osmium tags-filter in.osm.pbf -e filter.txt -o out.osm.pbf
"""

import contextlib
import io
import json
import runpy
import sys
from pathlib import Path

IMPOSM_DIR = Path(__file__).resolve().parent.parent / "imposm"


def load_mapping() -> dict:
    sys.path.insert(0, str(IMPOSM_DIR))
    out = io.StringIO()
    with contextlib.redirect_stdout(out):
        runpy.run_path(str(IMPOSM_DIR / "main.py"), run_name="__main__")
    return json.loads(out.getvalue())


def main() -> None:
    mapping = load_mapping()

    # key -> set of values (None means "any value")
    keys: dict[str, set[str] | None] = {}
    for table in mapping["tables"].values():
        mappings = [table["mapping"]] if "mapping" in table else table["type_mappings"].values()
        for m in mappings:
            for key, values in m.items():
                if "__any__" in values or keys.get(key, set()) is None:
                    keys[key] = None
                else:
                    keys.setdefault(key, set()).update(values)  # type: ignore[union-attr]

    print("# Generated by scripts/osm_filter.py from the imposm mapping. Do not edit.")
    for key in sorted(keys):
        values = keys[key]
        if values is None:
            print(f"nwr/{key}")
        else:
            print(f"nwr/{key}={','.join(sorted(values))}")


if __name__ == "__main__":
    main()
